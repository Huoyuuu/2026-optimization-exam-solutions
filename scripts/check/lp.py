def main():
    only = sys.argv[1:]
    for key, (A, b, c, names, unit, nt) in P.items():
        if only and key not in only:
            continue
        print(f"\n################ {key}")
        T1, T2 = two_phase(A, b, c, names, unit)
        art = [i for i in range(len(A)) if i not in unit]
        cols = [f"$u_{i + 1}$" for i in art] + (nt or [f"$x_{n[1:]}$" for n in names])
        head = "#import \"/book/lib.typ\": *\n"
        (GEN / f"lp-{key}-1.typ").write_text(head + T1.typst(cols) + "\n", encoding="utf-8", newline="\n")
        if T2 is not None:
            src = T2.typst(nt or [f"$x_{n[1:]}$" for n in names])
            (GEN / f"lp-{key}-2.typ").write_text(head + src + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
